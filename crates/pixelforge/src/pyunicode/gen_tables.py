# How tables.rs (next to this file) was generated. Kept to document it: it needs Python
# 3.11 (Unicode 14.0.0, the Python the oracles in tests/oracle/ were recorded with), which
# this repository no longer uses. Run it as below (it lived in scripts/ until 0.2.0).
"""Write crates/pixelforge/src/pyunicode/tables.rs from this Python's unicodedata.

The Rust port reproduces a few Python str behaviours that depend on Unicode properties
(str.isspace, str.isprintable for repr(), str.isdigit and the decimal digits int() and
float() accept). Rust's std does not expose those properties, so the tables are generated
here. Run with the Python the oracles were recorded with (3.11, Unicode 14.0.0):

    python3.11 crates/pixelforge/src/pyunicode/gen_tables.py
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent / "tables.rs"


def ranges(pred) -> list[tuple[int, int]]:
    out, start = [], None
    for c in range(0x110000):
        if pred(chr(c)):
            if start is None:
                start = c
        elif start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name: str, doc: str, rows: list[tuple[int, int]]) -> str:
    items = [f"(0x{a:X}, 0x{b:X})," for a, b in rows]
    lines, line = [], "   "
    for item in items:
        if len(line) + 1 + len(item) > 99:
            lines.append(line)
            line = "   "
        line += " " + item
    lines.append(line)
    body = "\n".join(lines)
    return f"/// {doc}\npub const {name}: &[(u32, u32)] = &[\n{body}\n];\n"


def main() -> None:
    zeros = [c for c in range(0x110000) if unicodedata.decimal(chr(c), None) == 0]
    assert all(unicodedata.decimal(chr(z + i), None) == i for z in zeros for i in range(10))
    assert sum(chr(c).isdecimal() for c in range(0x110000)) == 10 * len(zeros)
    parts = [
        "//! Generated by gen_tables.py (next to this file) from Python "
        f"{sys.version.split()[0]}, Unicode {unicodedata.unidata_version}. Do not edit.\n",
        "/// The Unicode version of the tables.\n"
        f'pub const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";\n',
        table("SPACE", "Inclusive ranges of the characters for which `str.isspace()` holds.",
              ranges(str.isspace)),
        table("NOT_PRINTABLE",
              "Inclusive ranges of the characters for which `str.isprintable()` is false.",
              ranges(lambda c: not c.isprintable())),
        table("DIGIT_NOT_DECIMAL",
              "Inclusive ranges of the characters with `str.isdigit()` but not "
              "`str.isdecimal()`.",
              ranges(lambda c: c.isdigit() and not c.isdecimal())),
        "/// The decimal digit zeros: every decimal digit is `zero + value` for one of these\n"
        "/// (each block of ten is contiguous).\n"
        "pub const DECIMAL_ZEROS: &[u32] = &[\n"
        + "".join(f"    0x{z:X},\n" for z in zeros) + "];\n",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
